#!/usr/bin/env python3
"""Bake grainifier profile JSONs into a C header for the darktable module.

    python darktable/gen_profiles_header.py grainifier/profiles/*-1pass.json -o darktable/grainifier_profiles.h

Per profile: σ_D(D) and skew(D) sampled on a fixed 0.05-D grid (0..3.5), the reliable-density
limit, the scanner pitch, and the grain kernel — the unit-variance zero-phase filter derived
from the measured noise power spectrum — truncated to KERNEL×KERNEL taps at the scanner pitch.
The module convolves hashed white noise with this kernel in film-µm coordinates, exactly what
grainifier/render.py does with an FFT.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from grainifier.render import GrainProfile  # noqa: E402

GRID = np.round(np.arange(0.0, 3.5 + 1e-9, 0.05), 3)
KERNEL = 15  # taps per axis at the profile's pitch (±7 px ≈ ±44 µm; autocorrelation is ~0 beyond lag 4)
DECIMATIONS = (1, 2, 3, 4, 6, 8, 12, 16)  # output pitch / scanner pitch for zoomed-out views
DEC_KERNEL = 9  # taps per axis for the decimated kernels


def decimated_kernel(kernel: np.ndarray, m: int, rng: np.random.Generator, size: int = 2048) -> tuple[np.ndarray, float]:
    """Kernel (on a lattice m× coarser than the scan pitch) whose white-noise convolution has the
    variance and autocorrelation of the fine grain field box-averaged over m×m cells — i.e. what
    the renderer produces when the output pixel is coarser than the scan. Returns (kernel, variance)."""
    from grainifier.render import _shaped_noise

    n = _shaped_noise((size, size), kernel.astype(np.float32), rng)
    if m > 1:
        s = size // m * m
        n = n[:s, :s].reshape(s // m, m, s // m, m).mean((1, 3))
    var = float(n.var())
    f = np.fft.rfft2(n - n.mean())
    power = (np.abs(f) ** 2) / n.size  # periodogram
    ac = np.fft.irfft2(power, s=n.shape) / n.size
    h = DEC_KERNEL // 2
    # zero-phase kernel from the (windowed) autocorrelation: sqrt of its spectrum
    win = np.zeros_like(ac)
    for dy in range(-h, h + 1):
        for dx in range(-h, h + 1):
            win[dy % n.shape[0], dx % n.shape[1]] = ac[dy % n.shape[0], dx % n.shape[1]]
    spec = np.maximum(np.fft.fft2(win).real, 0.0)
    k = np.fft.fftshift(np.fft.ifft2(np.sqrt(spec)).real)
    c = n.shape[0] // 2
    k = k[c - h : c + h + 1, c - h : c + h + 1]
    k = k / np.sqrt((k**2).sum()) * np.sqrt(var)  # unit-variance-noise ⊛ k has variance `var`
    return k.astype(np.float64), var


def c_ident(name: str) -> str:
    return "".join(ch if ch.isalnum() else "_" for ch in name)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("profiles", nargs="+")
    ap.add_argument("-o", "--output", required=True)
    a = ap.parse_args()

    out = ["/* generated by darktable/gen_profiles_header.py — do not edit */", "#pragma once", "",
           f"#define GRAINIFIER_GRID_N {len(GRID)}", f"#define GRAINIFIER_GRID_STEP 0.05f", f"#define GRAINIFIER_KERNEL {KERNEL}",
           f"#define GRAINIFIER_N_DEC {len(DECIMATIONS)}", f"#define GRAINIFIER_DEC_KERNEL {DEC_KERNEL}",
           "static const int grainifier_decimations[GRAINIFIER_N_DEC] = { " + ", ".join(str(m) for m in DECIMATIONS) + " };", ""]
    out.append("typedef struct grainifier_profile_t {")
    out.append("  const char *name;        /* label shown in the module */")
    out.append("  float pitch_um;          /* pixel pitch the statistics were measured at */")
    out.append("  float reliable_dmax;     /* density above which sigma/skew are held constant */")
    out.append(f"  float sigma[GRAINIFIER_GRID_N];   /* sigma_D at D = i * 0.05 */")
    out.append(f"  float skew[GRAINIFIER_GRID_N];")
    out.append(f"  float kernel[GRAINIFIER_KERNEL * GRAINIFIER_KERNEL]; /* unit sum of squares */")
    out.append(f"  float dec_kernel[GRAINIFIER_N_DEC][GRAINIFIER_DEC_KERNEL * GRAINIFIER_DEC_KERNEL]; /* per decimation, scaled so noise ⊛ k has the box-averaged variance */")
    out.append(f"  float dec_var[GRAINIFIER_N_DEC]; /* variance of the box-averaged field per decimation (m=1 → 1) */")
    out.append("} grainifier_profile_t;", )
    out.append("")
    entries = []
    for path in a.profiles:
        p = GrainProfile(path)
        doc = json.loads(Path(path).read_text())
        label = f"{doc.get('stock', p.name)} @ {doc.get('exposure_index', '')}".strip(" @")
        if "1pass" not in p.name and "push" not in p.name:
            label += " (softer scan)"
        if "push" in p.name:
            label += " (push 2)"
        sig = p.sigma_at(GRID.astype(np.float32))
        sk = p.skew_at(GRID.astype(np.float32))
        k = p.kernel
        c = k.shape[0] // 2
        h = KERNEL // 2
        kk = k[c - h : c + h + 1, c - h : c + h + 1].astype(np.float64)
        kk /= np.sqrt((kk**2).sum())
        ident = c_ident(p.name)
        out.append(f"static const grainifier_profile_t grainifier_profile_{ident} = {{")
        out.append(f'  "{label}", {p.pitch_um:.4f}f, {p.reliable_dmax:.2f}f,')
        out.append("  { " + ", ".join(f"{v:.5f}f" for v in sig) + " },")
        out.append("  { " + ", ".join(f"{v:.4f}f" for v in sk) + " },")
        out.append("  { " + ", ".join(f"{v:.6f}f" for v in kk.ravel()) + " },")
        rng = np.random.default_rng(1)
        out.append("  {")
        variances = []
        for m in DECIMATIONS:
            dk, var = decimated_kernel(p.kernel, m, rng)
            variances.append(var)
            out.append(f"    /* m={m}, variance {var:.4f} */ {{ " + ", ".join(f"{v:.6f}f" for v in dk.ravel()) + " },")
        out.append("  },")
        out.append("  { " + ", ".join(f"{v:.5f}f" for v in variances) + " },")
        out.append("};")
        entries.append(f"&grainifier_profile_{ident}")
    out.append("")
    out.append(f"#define GRAINIFIER_N_PROFILES {len(entries)}")
    out.append("static const grainifier_profile_t *grainifier_profiles[GRAINIFIER_N_PROFILES] = { " + ", ".join(entries) + " };")
    out.append("")
    Path(a.output).write_text("\n".join(out))
    print(f"wrote {a.output}: {len(entries)} profiles, grid {len(GRID)}, kernel {KERNEL}x{KERNEL}")


if __name__ == "__main__":
    main()
